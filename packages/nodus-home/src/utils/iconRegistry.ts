/**
 * Safely resolves an icon by PascalCase, camelCase, or kebab-case name with fallback.
 */
export function getRegisteredIcon(iconName?: string): React.ComponentType<any> {
  if (!iconName) return AppWindow;

  // Direct match
  if (ICON_REGISTRY[iconName]) {
    return ICON_REGISTRY[iconName];
  }

  // Normalized PascalCase match (e.g. "settings" -> "Settings", "gamepad-2" -> "Gamepad2")
  const normalized = iconName
    .replace(/(?:^|[-_])(\w)/g, (_, c) => c.toUpperCase())
    .replace(/[-_]/g, '');

  if (ICON_REGISTRY[normalized]) {
    return ICON_REGISTRY[normalized];
  }

  return AppWindow;
}
